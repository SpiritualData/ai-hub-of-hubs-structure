"""Print (or with --write, put into README.md between its markers) the results table of the context-assembler seat, read from the records.

    python3 evaluation/context_assembler/results_table.py [component] --write

The component defaults to ``context_assembler``, the one pooled component. A row counts only on the current case files (``cases_sha``).

Reads ``esoi/results.csv`` (pass count, details with nDCG@10 and recall@10, written by ``esoi run --record`` from ``aggregate``) and
``esoi/per_case.csv`` (the median seconds per query), for the latest full-set row of each arm on the current case file. Runs nothing.
"""
import csv
import math
import statistics
import sys
from pathlib import Path

COMPONENT = next((a for a in sys.argv[1:] if not a.startswith("--")), "context_assembler")
ROOT = Path(__file__).resolve().parent.parent.parent
HERE = ROOT / "evaluation" / COMPONENT
ARMS = ["bm25", "bm25@analyzer=english", "vector", "hybrid", "hybrid@vector_weight=1.0", "composite"]
START, END = "<!-- results:start -->", "<!-- results:end -->"


def wilson(passed, total, z=1.96):
    p = passed / total
    centre = (p + z * z / (2 * total)) / (1 + z * z / total)
    half = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / (1 + z * z / total)
    return centre - half, centre + half


def read(name):
    with (ROOT / "esoi" / name).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def table():
    sys.path.insert(0, str(ROOT.parent / "evolvable-structure" / "implementations" / "python"))
    from esoi.leaderboard import cases_digest
    cases_sha = cases_digest(COMPONENT, ROOT / "evaluation")
    results = [r for r in read("results.csv") if r["component"] == COMPONENT and not r["sample"] and r["cases_sha"] == cases_sha]
    per_case = read("per_case.csv")
    if not results:
        return ("No arm is recorded on the pooled case set yet: its papers and paraphrase sources read a private collection, so a run needs "
                "that collection's settings. Rows recorded earlier on the public benchmark alone sit in `esoi/results.csv` under their own "
                "case hash and are not comparable with the pooled number.")
    lines = ["| arm | pass (relevant in top 5) | 95% Wilson | nDCG@10 | recall@10 | median s/query | cost |", "|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        rows = [r for r in results if r["impl"] == arm]
        if not rows:
            continue
        row = rows[-1]
        passed, total = int(row["passed"]), int(row["cases"])
        low, high = wilson(passed, total)
        details = dict(part.split("=", 1) for part in row["details"].split("; ") if "=" in part)
        seconds = [float(c["seconds"]) for c in per_case if c["component"] == COMPONENT and c["impl"] == arm and c["cases_sha"] == cases_sha and not c["sample"]]
        lines.append(f"| {arm} | {passed}/{total} ({passed / total:.1%}) | {low:.1%} to {high:.1%} | {details.get('ndcg_at_10', '')} | "
                     f"{details.get('recall_at_10', '')} | {statistics.median(seconds):.1f} | ${float(row['cost_usd'] or 0):.2f} |")
    return "\n".join(lines)


if __name__ == "__main__":
    text = table()
    print(text)
    if "--write" in sys.argv:
        readme = HERE / "README.md"
        body = readme.read_text(encoding="utf-8")
        block = f"{START}\n{text}\n{END}"
        if START in body:
            head, rest = body.split(START, 1)
            body = head + block + rest.split(END, 1)[1]
        else:
            body = body.rstrip("\n") + f"\n\n## Results (generated by `evaluation/context_assembler/results_table.py` from the records)\n\n{block}\n"
        readme.write_text(body, encoding="utf-8")
