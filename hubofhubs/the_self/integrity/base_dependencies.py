"""The base ``dependencies`` of ``pyproject.toml``, derived from what the selected arms declare, never typed by hand.

``pip install hubofhubs`` must bring every library the currently selected arm of every solution imports, so the hub works on a plain
install. Each arm declares its Python needs with ``REQUIRES`` (``hubofhubs/the_self/assembler/arm_needs.py``) and each need names the extra
of ``pyproject.toml`` that provides it; the extras stay for the alternatives that are not selected. This module reads the selected arms, takes
the libraries of the extras they name, and rewrites the lines of ``dependencies`` between two marker comments (``scripts/sync_dependencies.py``;
a test fails when the file is not current). A need declared optional (``required=False``) is left out: the arm degrades honestly without it.
Standard library plus the hub and ``esoi``."""
import re
import tomllib
from typing import Dict, List, Tuple

from esoi import AssemblyConfig
from esoi import requirements as needs

from hubofhubs.the_self.assembler.resolution import assembler

BEGIN, END = "# selected-arms:start (generated by scripts/sync_dependencies.py)", "# selected-arms:end"


def selected_extras() -> Dict[str, List[str]]:
    """``{extra: [arm labels]}`` for every required Python need of the selected arm of every solution."""
    found: Dict[str, List[str]] = {}
    for member in assembler().closure(AssemblyConfig(), None, (), False):
        for item in needs.declared(member.target):
            if isinstance(item, needs.Python) and item.required and item.extra:
                found.setdefault(item.extra, []).append(member.label)
    return found


def library_name(spec: str) -> str:
    return re.split(r"[<>=!~\[ ;@]", spec, maxsplit=1)[0].strip().lower().replace("_", "-")


def wanted(pyproject: str) -> List[str]:
    """The library specs, from the extras of ``pyproject`` that the selected arms name, one per library."""
    table = tomllib.loads(pyproject)["project"]["optional-dependencies"]
    chosen: Dict[str, str] = {}
    for extra in selected_extras():
        for spec in table[extra]:
            chosen.setdefault(library_name(spec), spec)
    return sorted(chosen.values(), key=library_name)


def block(pyproject: str) -> str:
    return "\n".join("    " + line for line in [BEGIN, *[f'"{spec}",' for spec in wanted(pyproject)], END])


def current(pyproject: str) -> Tuple[bool, str]:
    """``(is current, the file as it should read)``: the marked lines of ``dependencies`` replaced by the derived ones."""
    pattern = re.compile(re.escape("    " + BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(pyproject):
        raise ValueError("pyproject.toml has no selected-arms markers inside dependencies")
    rewritten = pattern.sub(lambda _m: block(pyproject), pyproject)
    return rewritten == pyproject, rewritten
